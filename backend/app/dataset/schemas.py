from pydantic import BaseModel, Field


class DestinationSeed(BaseModel):
    """
    A single tourist destination generated by the LLM.
    """

    name: str = Field(
        description="Official destination name."
    )

    category: str = Field(
        description=(
            "One of: city, beach, island, mountain, "
            "national_park, unesco, ski, nature, "
            "historic, desert, adventure"
        )
    )


class CountryDestinations(BaseModel):
    """
    All destinations generated for a country.
    """

    country: str

    destinations: list[DestinationSeed]